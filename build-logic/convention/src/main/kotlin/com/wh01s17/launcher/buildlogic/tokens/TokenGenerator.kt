package com.wh01s17.launcher.buildlogic.tokens

import org.tomlj.TomlTable

/** Salida del generador: código Kotlin de los tokens y recursos de color de Android. */
class GeneratedTokens(
    val kotlin: String,
    val colorResources: String,
)

/**
 * Convierte el tema `wh01s17` en `WhTokens` (plan.md §4.1).
 *
 * Tipos por regla, sin tablas por clave:
 * - `"#RRGGBB"` → `Color`; `"hyprland.active-border[-foreground]"` → `WhBorderSource`.
 * - número en una clave `*alpha` o `scale` → `Float`; en la tabla `font` → `sp`; en el resto → `dp`.
 * - booleano y otros textos → tal cual.
 */
object TokenGenerator {
    private val HEX = Regex("^#[0-9a-fA-F]{6}$")
    private val RGBA = Regex("rgba\\(([0-9a-fA-F]{8})\\)")
    private val ANGLE = Regex("(\\d+(?:\\.\\d+)?)deg")
    private val BORDER_REFS = setOf("hyprland.active-border", "hyprland.active-border-foreground")
    private val BORDER_KEYS = setOf("hyprland_active_border", "hyprland_inactive_border")
    private val RESOURCE_KEY = Regex("^[a-z][a-z0-9_]*$")

    fun generate(
        source: ThemeSource,
        packageName: String,
    ): GeneratedTokens = GeneratedTokens(kotlin(source, packageName), colorResources(source))

    private fun kotlin(
        source: ThemeSource,
        packageName: String,
    ): String =
        buildString {
            appendLine("// <auto-generated> por :core:designsystem:generateTokens desde theme/wh01s17. No editar a mano.")
            appendLine("package $packageName")
            appendLine()
            appendLine("import androidx.compose.ui.graphics.Color")
            appendLine("import androidx.compose.ui.unit.dp")
            appendLine("import androidx.compose.ui.unit.sp")
            appendLine()
            appendLine("/** Fuente de un borde que el tema toma de otro lugar. */")
            appendLine("internal enum class WhBorderSource { HyprlandActive }")
            appendLine()
            appendLine("internal object WhTokens {")
            appendObject("Colors", "colors", colorProperties(source.colors))
            appendObject("Border", "border", borderProperties(source))
            for ((name, table) in source.sections.toSortedMap()) {
                appendObject(pascal(name), name, properties(name, table))
            }
            appendLine("}")
        }

    private fun StringBuilder.appendObject(
        objectName: String,
        origin: String,
        lines: List<String>,
    ) {
        appendLine("    /** Desde `$origin`. */")
        appendLine("    object $objectName {")
        lines.forEach { appendLine("        $it") }
        appendLine("    }")
        appendLine()
    }

    private fun colorProperties(colors: TomlTable): List<String> =
        colors
            .keySet()
            .filter { it !in BORDER_KEYS }
            .sorted()
            .map { property("colors", it, colors.get(it)) }

    private fun borderProperties(source: ThemeSource): List<String> {
        val active = source.colors.getString("hyprland_active_border") ?: throw TokenException("colors.toml: falta hyprland_active_border")
        val inactive = source.colors.getString("hyprland_inactive_border") ?: throw TokenException("colors.toml: falta hyprland_inactive_border")
        val stops = RGBA.findAll(active).map { it.groupValues[1] }.toList()
        if (stops.size != 2) throw TokenException("hyprland_active_border: se esperan 2 colores rgba(...), hay ${stops.size}")
        val angle = ANGLE.find(active)?.groupValues?.get(1) ?: throw TokenException("hyprland_active_border: falta el ángulo (45deg)")
        val inactiveStop = RGBA.find(inactive)?.groupValues?.get(1) ?: throw TokenException("hyprland_inactive_border: se espera rgba(...)")
        return listOf(
            "val activeStart = ${rgbaColor(stops[0])}",
            "val activeEnd = ${rgbaColor(stops[1])}",
            "const val activeAngleDegrees = ${angle.toFloat()}f",
            "val inactive = ${rgbaColor(inactiveStop)}",
            "val rounding = ${source.rounding}.dp",
        )
    }

    /** `rrggbbaa` (CSS/Hyprland) → `Color(0xAARRGGBB)`. */
    private fun rgbaColor(rrggbbaa: String): String =
        "Color(0x${rrggbbaa.substring(6).uppercase()}${rrggbbaa.substring(0, 6).uppercase()})"

    private fun properties(
        section: String,
        table: TomlTable,
    ): List<String> = table.keySet().sorted().map { property(section, it, table.get(it)) }

    private fun property(
        section: String,
        key: String,
        value: Any?,
    ): String {
        val name = camel(key)
        return when (value) {
            is Boolean -> "val $name = $value"
            is String -> "val $name = ${stringValue(section, key, value)}"
            is Long -> "val $name = ${number(section, key, value.toDouble(), value.toString())}"
            is Double -> "val $name = ${number(section, key, value, value.toString())}"
            else -> throw TokenException("$section.$key: tipo no soportado (${value?.javaClass?.simpleName})")
        }
    }

    private fun stringValue(
        section: String,
        key: String,
        value: String,
    ): String =
        when {
            HEX.matches(value) -> "Color(0xFF${value.substring(1).uppercase()})"
            value in BORDER_REFS -> "WhBorderSource.HyprlandActive"
            value.startsWith("hyprland.") -> throw TokenException("$section.$key: referencia desconocida `$value`")
            else -> "\"${value.replace("\\", "\\\\").replace("\"", "\\\"")}\""
        }

    private fun number(
        section: String,
        key: String,
        asDouble: Double,
        literal: String,
    ): String {
        val isInteger = !literal.contains('.')
        return when {
            key.endsWith("alpha") || key == "scale" -> {
                if (key.endsWith("alpha") && asDouble !in 0.0..1.0) throw TokenException("$section.$key: alfa fuera de 0..1 ($literal)")
                "${asDouble.toFloat()}f"
            }
            section == "font" -> "${if (isInteger) literal else asDouble}.sp"
            else -> "${if (isInteger) literal else asDouble}.dp"
        }
    }

    private fun colorResources(source: ThemeSource): String =
        buildString {
            appendLine("""<?xml version="1.0" encoding="utf-8"?>""")
            appendLine("<!-- Generado por :core:designsystem:generateTokens desde theme/wh01s17/colors.toml. No editar a mano. -->")
            appendLine("<resources>")
            for (key in source.colors.keySet().sorted()) {
                val value = source.colors.get(key)
                if (value !is String || !HEX.matches(value)) continue
                if (!RESOURCE_KEY.matches(key)) throw TokenException("colors.$key: nombre de recurso inválido")
                appendLine("""    <color name="wh_$key">#FF${value.substring(1).uppercase()}</color>""")
            }
            appendLine("</resources>")
        }

    /** `dark-background` / `dark_background` → `darkBackground`. */
    internal fun camel(key: String): String {
        val parts = key.split('-', '_').filter { it.isNotEmpty() }
        require(parts.isNotEmpty()) { "clave vacía" }
        return parts.first().lowercase() + parts.drop(1).joinToString("") { it.replaceFirstChar(Char::uppercase) }
    }

    internal fun pascal(key: String): String = camel(key).replaceFirstChar(Char::uppercase)
}
